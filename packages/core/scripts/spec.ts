/**
 * pnpm spec:build      regenerates the requirement registry and spec/STATUS.md from spec/pap-<version>/*.md
 * pnpm spec:check      fails when the official snapshot, the spec, the registry, the checks and the plan disagree
 * pnpm spec:reconciled records that spec/pap-<version> now matches the official snapshot in spec/source
 */
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { checks } from "../src/conformance/checks/index.ts";
import { CURRENT_LEG, PLAN } from "../src/conformance/plan.ts";
import { formatStatus } from "../src/conformance/report.ts";
import { isCompanyDuty } from "../src/conformance/runner.ts";
import { parseSpec } from "../src/conformance/spec/parse.ts";
import { MUTANTS, NOT_MUTATED } from "./mutants.data.ts";
import type { Requirement } from "../src/conformance/types.ts";

const SPEC_VERSION = "0.1";
const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const specDir = join(root, `spec/pap-${SPEC_VERSION}`);
const generatedPath = join(root, "packages/core/src/conformance/requirements.generated.ts");
const statusPath = join(root, "spec/STATUS.md");
const sourceDir = join(root, "spec/source");
const readmePath = join(specDir, "README.md");
const RECONCILED = /<!-- reconciled-sha256: ([0-9a-f]+|RECONCILED_HASH) -->/;

const mode = process.argv[2];
if (mode !== "build" && mode !== "check" && mode !== "reconciled") {
	console.error("usage: spec.ts build|check|reconciled");
	process.exit(2);
}

const sha256 = (data: string | Buffer) => createHash("sha256").update(data).digest("hex");
const sums = readFileSync(join(sourceDir, "SHA256SUMS"), "utf8");

if (mode === "reconciled") {
	const readme = readFileSync(readmePath, "utf8");
	writeFileSync(readmePath, readme.replace(RECONCILED, `<!-- reconciled-sha256: ${sha256(sums)} -->`));
	console.log(`✓ recorded spec/source snapshot ${sha256(sums).slice(0, 12)} as reconciled`);
	process.exit(0);
}

const files = readdirSync(specDir)
	.filter((f) => f.endsWith(".md"))
	.sort()
	.map((f) => ({ file: relative(root, join(specDir, f)), markdown: readFileSync(join(specDir, f), "utf8") }));
const { requirements, errors } = parseSpec(files);

function generated(reqs: Requirement[]): string {
	return [
		"// Generated by `pnpm spec:build` from spec/pap-*.md. Do not edit.",
		'import type { Requirement } from "./types.ts";',
		"",
		`export const SPEC_VERSION = ${JSON.stringify(SPEC_VERSION)};`,
		"",
		"export const REQUIREMENTS: Requirement[] = [",
		...reqs.map((r) => `\t${JSON.stringify(r)},`),
		"];",
		"",
	].join("\n");
}

const outputs = [
	{ path: generatedPath, content: generated(requirements) },
	{ path: statusPath, content: `${formatStatus(requirements, SPEC_VERSION, CURRENT_LEG)}\n` },
];

if (errors.length > 0) {
	console.error(`✗ The spec has ${errors.length} formatting error(s):\n${errors.map((e) => `  ${e}`).join("\n")}`);
	process.exit(1);
}

if (mode === "build") {
	for (const { path, content } of outputs) writeFileSync(path, content);
	console.log(`✓ ${requirements.length} requirements from ${files.length} files → ${relative(root, generatedPath)}, ${relative(root, statusPath)}`);
	process.exit(0);
}

// check
const problems: string[] = [];

// The snapshot is the official text, byte for byte.
for (const line of sums.trim().split("\n")) {
	const [hash, file] = line.split(/\s+/);
	let actual = "";
	try {
		actual = sha256(readFileSync(join(sourceDir, file!)));
	} catch {
		// reported below
	}
	if (actual !== hash) problems.push(`spec/source/${file!.replace(/^\.\//, "")} differs from SHA256SUMS. Never edit the official snapshot; refresh it with the spec-snapshot workflow`);
}
const recorded = RECONCILED.exec(readFileSync(readmePath, "utf8"))?.[1];
if (recorded !== sha256(sums)) {
	problems.push("the official spec in spec/source changed since spec/pap-0.1 was last reconciled. Compare them, update spec/pap-0.1, then run: pnpm spec:reconciled");
}
const ids = new Set(requirements.map((r) => r.id));
const byId = new Map(requirements.map((r) => [r.id, r]));
const at = (id: string) => {
	const r = byId.get(id);
	return r ? `${r.file}:${r.line}` : id;
};

for (const { path, content } of outputs) {
	let current = "";
	try {
		current = readFileSync(path, "utf8");
	} catch {
		// missing counts as stale
	}
	if (current !== content) problems.push(`${relative(root, path)} is out of date. Run: pnpm spec:build`);
}

const checkIds = new Set<string>();
for (const c of checks) {
	if (checkIds.has(c.id)) problems.push(`check ${c.id} is defined twice`);
	checkIds.add(c.id);
	if (c.covers.length === 0) problems.push(`check ${c.id} covers no requirement`);
	for (const id of c.covers) if (!ids.has(id)) problems.push(`check ${c.id} covers unknown requirement ${id} (renamed or removed from the spec?)`);
}

for (const [id, entry] of Object.entries(PLAN)) {
	const requirement = byId.get(id);
	if (!requirement) {
		problems.push(`plan.ts schedules unknown requirement ${id} (renamed or removed from the spec?)`);
		continue;
	}
	if (requirement.role === "agent") problems.push(`plan.ts schedules ${id}, which is agent-side (${at(id)})`);
	const covered = checks.some((c) => c.covers.includes(id) && c.leg <= CURRENT_LEG);
	if ("leg" in entry && entry.leg <= CURRENT_LEG && !covered) {
		problems.push(`${id} is planned for leg ${entry.leg}, which has shipped, but no check covers it (${at(id)})`);
	}
}

const mutated = new Set(MUTANTS.map((m) => m.caughtBy));
for (const m of MUTANTS) if (!checkIds.has(m.caughtBy)) problems.push(`mutant "${m.name}" names unknown check ${m.caughtBy}`);
for (const id of Object.keys(NOT_MUTATED)) {
	if (!checkIds.has(id)) problems.push(`NOT_MUTATED names unknown check ${id}`);
	if (mutated.has(id)) problems.push(`${id} has a mutant, so remove it from NOT_MUTATED`);
}
for (const c of checks.filter((c) => c.leg <= CURRENT_LEG && !mutated.has(c.id) && !NOT_MUTATED[c.id])) {
	problems.push(`check ${c.id} has no mutant. Add one to scripts/mutants.data.ts that only this check catches, or explain in NOT_MUTATED why none can exist`);
}

const unplanned = requirements.filter((r) => isCompanyDuty(r) && !checks.some((c) => c.covers.includes(r.id)) && !PLAN[r.id]);
for (const r of unplanned) {
	problems.push(`${r.id} (${r.level}, ${r.role}) has no check and no plan entry. Add a check or schedule it in plan.ts (${r.file}:${r.line})`);
}

if (problems.length > 0) {
	console.error(`✗ spec:check found ${problems.length} problem(s):\n${problems.map((p) => `  • ${p}`).join("\n")}`);
	process.exit(1);
}
const duties = requirements.filter(isCompanyDuty).length;
console.log(`✓ spec:check: ${requirements.length} requirements, ${duties} company duties, ${checks.length} checks, ${MUTANTS.length} mutants, plan consistent`);
